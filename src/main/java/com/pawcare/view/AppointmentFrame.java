    private void filterPets() {
        int customerId=Ui.id(cmbCustomer); cmbPet.removeAllItems();
        for(Pet pet:allPets) if(pet.getCustomerId()==customerId) cmbPet.addItem(pet);
        cmbPet.setSelectedIndex(-1);
    }
    private void refresh() {
        final int version=++loadVersion; String search=txtSearch.getText(); lblStatus.setText("Loading appointments...");
        Tasks.run(this,btnSearch,() -> new Data(controller.list(search),lookups.customers(),lookups.pets(),lookups.services()),data -> {
            if(version!=loadVersion) return;
            rows=data.appointments; allPets=data.pets; cmbCustomer.removeAllItems(); cmbService.removeAllItems();
            for(Customer c:data.customers) cmbCustomer.addItem(c); for(GroomingService s:data.services) cmbService.addItem(s);
            tableModel.setRowCount(0);
            for(Appointment a:rows) tableModel.addRow(new Object[]{a.getId(),a.getCustomerName(),a.getPetName(),a.getServiceName(),a.getDate(),a.getTime(),a.getStatus(),a.getBookedPrice()});
            clear(); lblStatus.setText(rows.size()+" appointments • Times use Asia/Colombo • Prices are preserved when booked.");
        });
    }
    private void save(boolean update) {
        try {
            if(update && selectedId==0) throw new InvalidAppointmentException("Select an appointment to update.");
            Appointment a=new Appointment(); a.setId(update?selectedId:0); a.setCustomerId(Ui.id(cmbCustomer)); a.setPetId(Ui.id(cmbPet)); a.setServiceId(Ui.id(cmbService));
            a.setDate(Validation.date(txtDate.getText())); a.setTime(Validation.time(txtTime.getText())); a.setStatus((String)cmbStatus.getSelectedItem());
            Tasks.run(this,update?btnUpdate:btnSave,() -> { controller.save(a); return a; },saved -> { txtSearch.setText(""); refresh(); Ui.message(this,"Appointment saved."); });
        } catch(Exception e) { Ui.error(this,e); }
    }
    private void remove(boolean delete) {
        if(selectedId==0) { Ui.message(this,"Select an appointment first."); return; }
        int id=selectedId;
        if(!Ui.confirm(this,delete?"Permanently delete this appointment?":"Cancel this appointment? Its history will remain visible.")) return;
        Tasks.run(this,delete?btnDelete:btnCancel,() -> { if(delete) controller.delete(id); else controller.cancel(id); return true; },ok -> refresh());
    }
    private void selectRow() {
        int row=tblAppointments.getSelectedRow(); if(row<0) return;
        Appointment a=rows.get(tblAppointments.convertRowIndexToModel(row)); selectedId=a.getId(); txtAppointmentId.setText(""+a.getId());
        Ui.select(cmbCustomer,a.getCustomerId()); Ui.select(cmbPet,a.getPetId()); Ui.select(cmbService,a.getServiceId());
        txtDate.setText(a.getDate().toString()); txtTime.setText(a.getTime().format(java.time.format.DateTimeFormatter.ofPattern("HH:mm"))); cmbStatus.setSelectedItem(a.getStatus());
    }
    private void clear() {
        selectedId=0; tblAppointments.clearSelection(); txtAppointmentId.setText("New"); cmbCustomer.setSelectedIndex(-1); cmbPet.removeAllItems(); cmbService.setSelectedIndex(-1);
        txtDate.setText(AppClock.today().plusDays(1).toString()); txtTime.setText("09:00"); cmbStatus.setSelectedItem("Pending");
    }
    private static class Data {
        final List<Appointment> appointments; final List<Customer> customers; final List<Pet> pets; final List<GroomingService> services;
        Data(List<Appointment> a,List<Customer> c,List<Pet> p,List<GroomingService> s) { appointments=a;customers=c;pets=p;services=s; }
    }

