    public void loadDashboardData() {
        if(loading) return; loading=true; btnRefresh.setEnabled(false);
        new SwingWorker<String[],Void>() {
            protected String[] doInBackground() throws Exception { return controller.loadDashboardData(); }
            protected void done() {
                loading=false; btnRefresh.setEnabled(true); if(!isDisplayable()) return;
                try { String[] v=get(); JLabel[] labels={lblTotalCustomers,lblTotalPets,lblTodayAppointments,lblPendingAppointments,lblCompletedAppointments,lblTodayRevenue};
                    for(int i=0;i<labels.length;i++) labels[i].setText(v[i]);
                    lblStatus.setText("Updated "+AppClock.now().format(java.time.format.DateTimeFormatter.ofPattern("HH:mm:ss"))+" • Refreshes every 5 seconds • Asia/Colombo");
                } catch(Exception ex) { ex.printStackTrace(); lblStatus.setText("Database unavailable. Check MySQL and use Refresh to try again."); }
            }
        }.execute();
    }
    private void changePassword() {
        if(Session.getUser()==null) return;
        JPasswordField current=new JPasswordField(),next=new JPasswordField(),confirm=new JPasswordField();
        Object[] fields={"Current password",current,"New password (at least 8 characters)",next,"Confirm new password",confirm};
        if(JOptionPane.showConfirmDialog(this,fields,"Change password",JOptionPane.OK_CANCEL_OPTION)!=JOptionPane.OK_OPTION) return;
        char[] old=current.getPassword(),fresh=next.getPassword(),repeat=confirm.getPassword();
        boolean matches=Arrays.equals(fresh,repeat); Arrays.fill(repeat,'\0');
        if(!matches) { Arrays.fill(old,'\0'); Arrays.fill(fresh,'\0'); Ui.message(this,"New passwords do not match."); return; }
        User user=Session.getUser();
        Tasks.run(this,btnPassword,() -> { try { new LoginController().changePassword(user,old,fresh); return true; } finally { Arrays.fill(old,'\0'); Arrays.fill(fresh,'\0'); } },ok -> Ui.message(this,"Password changed. Use it the next time you sign in."));
    }

