    private void refresh() {
        final int version=++loadVersion; String search=txtSearch.getText(); lblStatus.setText("Loading records...");
        Tasks.run(this,btnSearch,() -> { return controller.list(search); },data -> {
            if(version!=loadVersion) return;
            rows=data;
            tableModel.setRowCount(0);
            for(GroomingService v:rows) tableModel.addRow(new Object[]{v.getId(),v.getServiceName(),v.getDescription(),v.getPrice(),v.getDurationMinutes()});
            clear(); lblStatus.setText(rows.size()+" records • Select a row to update or delete.");
        });
    }
    private void save(boolean update) {
        try {
            if(update && selectedId==0) throw new ValidationException("Select a table row to update.");
            GroomingService v=new GroomingService(); v.setId(update?selectedId:0); v.setServiceName(txtServiceName.getText()); v.setDescription(txtDescription.getText()); v.setPrice(Validation.money(txtPrice.getText(),"Price")); v.setDurationMinutes(Validation.integer(txtDuration.getText(),"Duration",5,480));
            controller.validate(v);
            Tasks.run(this,update?btnUpdate:btnSave,() -> { controller.save(v); return v; },saved -> { txtSearch.setText(""); refresh(); Ui.message(this,"Record saved successfully."); });
        } catch(Exception ex) { Ui.error(this,ex); }
    }
    private void remove() {
        if(selectedId==0) { Ui.message(this,"Select a record first."); return; }
        final int id=selectedId;
        if(!Ui.confirm(this,"Delete the selected record? Linked records must be removed first.")) return;
        Tasks.run(this,btnDelete,() -> { controller.delete(id); return true; },ok -> refresh());
    }
    private void selectRow() {
        int row=tblServices.getSelectedRow(); if(row<0) return;
        GroomingService v=rows.get(tblServices.convertRowIndexToModel(row)); selectedId=v.getId(); txtServiceId.setText(""+v.getId()); txtServiceName.setText(v.getServiceName()); txtDescription.setText(v.getDescription()); txtPrice.setText(v.getPrice().toPlainString()); txtDuration.setText(""+v.getDurationMinutes());
    }
    private void clear() { selectedId=0; tblServices.clearSelection(); txtServiceId.setText("New"); txtServiceName.setText(""); txtDescription.setText(""); txtPrice.setText(""); txtDuration.setText(""); }

